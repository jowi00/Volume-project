rng(0)

scriptFolder = fileparts(mfilename('fullpath'));
root = scriptFolder;

% Support scripts stored either in the project root or in a code subfolder
if ~isfolder(fullfile(root, 'raw')) && ~isfolder(fullfile(root, 'results'))
    parentFolder = fileparts(scriptFolder);
    if isfolder(fullfile(parentFolder, 'raw')) || isfolder(fullfile(parentFolder, 'results'))
        root = parentFolder;
    end
end

%% Load camera poses

posesFolder = fullfile(root, 'results', 'rgbd_slam_hibrido');

if ~isfile(fullfile(posesFolder, 'slam_poses.mat'))
    posesFolder = fullfile(root, 'results', 'rgbd_slam');
end

poseFile = fullfile(posesFolder, 'slam_poses.mat');

if ~isfile(poseFile)
    error(['slam_poses.mat was not found. Run slam_rgbd.m first and then ' ...
           'refinar_poses_hibridas.m. Expected file: %s'], poseFile)
end

load(poseFile, ...
    'camPoses', ...
    'keyFrameIDs', ...
    'rgbIdx', ...
    'depthIdx');

%% Load the fused multi-view map

mapFile = fullfile( ...
    root, ...
    'results', ...
    'fusion_rgbd_hibrida', ...
    'mapa_consistente.ply');

if ~isfile(mapFile)
    error(['mapa_consistente.ply was not found. Run fusion_rgbd.m first. ' ...
           'Expected file: %s'], mapFile)
end

mapa = pcread(mapFile);

mapXYZ = double(reshape(mapa.Location, [], 3));
mapRGB = double(reshape(mapa.Color, [], 3));

validMap = all(isfinite(mapXYZ), 2);

mapXYZ = mapXYZ(validMap, :);
mapRGB = mapRGB(validMap, :);

%% Locate persistent red points

R = mapRGB(:,1);
G = mapRGB(:,2);
B = mapRGB(:,3);

redMap = R > 100;
redMap = redMap & R > 1.6*G;
redMap = redMap & R > 1.5*B;
redMap = redMap & R-G > 30;
redMap = redMap & R-B > 25;

redXYZ = mapXYZ(redMap, :);
redRGB = uint8(mapRGB(redMap, :));

if size(redXYZ,1) < 50
    error('Not enough red points were found in the fused map.')
end

%% Separate disconnected red objects

redCloud = pointCloud( ...
    single(redXYZ), ...
    'Color', redRGB);

labels = pcsegdist(redCloud, 0.12);

clusterIDs = unique(labels);
clusterIDs = clusterIDs(clusterIDs > 0);

if isempty(clusterIDs)
    error('No valid red point clusters were found.')
end

clusterSizes = zeros(numel(clusterIDs), 1);

for i = 1:numel(clusterIDs)
    clusterSizes(i) = nnz(labels == clusterIDs(i));
end

[~, largestIndex] = max(clusterSizes);

targetLabel = clusterIDs(largestIndex);
targetMask = labels == targetLabel;

targetXYZ = redXYZ(targetMask, :);

targetWorld = median(targetXYZ, 1);

fprintf('========== FIRE EXTINGUISHER LOCALIZATION ==========\n')
fprintf('Persistent red points: %d\n', size(targetXYZ,1))
fprintf('Global centre: X %.3f | Y %.3f | Z %.3f m\n\n', ...
    targetWorld(1), ...
    targetWorld(2), ...
    targetWorld(3))

%% RGB-D calibration

fx = 306.000244140625;
fy = 306.1123352050781;
cx = 318.4753112792969;
cy = 201.36949157714844;

Dcolor = [ ...
    -1.2477725744247437, ...
     0.8747861981391907, ...
    -9.421713184565306e-05, ...
    -0.00014916047803126276, ...
    -0.2381284087896347, ...
    -1.2307056188583374, ...
     0.8520383238792419, ...
    -0.2296648770570755];

minDepth = 0.5;
maxDepth = 6.0;

%% RGB-D files

rgbFolder = fullfile( ...
    root, ...
    'raw', ...
    'eval', ...
    'camera_color_image_raw');

depthFolder = fullfile( ...
    root, ...
    'raw', ...
    'eval', ...
    'camera_depth_image_raw');

rgbFiles = dir(fullfile(rgbFolder, '*.png'));
depthFiles = dir(fullfile(depthFolder, '*.png'));

[~, order] = sort({rgbFiles.name});
rgbFiles = rgbFiles(order);

[~, order] = sort({depthFiles.name});
depthFiles = depthFiles(order);

%% Measurement variables

n = numel(keyFrameIDs);

numPoints = zeros(n,1);

heightM = nan(n,1);
diameterM = nan(n,1);
volumeL = nan(n,1);

candidate = false(n,1);
objectPoints = cell(n,1);

fprintf('========== BASELINE MEASUREMENT PER KEYFRAME ==========\n')

%% Individual keyframe measurements

for k = 1:n

    frame = double(keyFrameIDs(k));

    targetCamera = transformPointsInverse( ...
        camPoses(k), ...
        targetWorld);

    if ~all(isfinite(targetCamera))
        continue
    end

    if targetCamera(3) <= minDepth || targetCamera(3) >= maxDepth
        continue
    end

    rgbFile = fullfile( ...
        rgbFiles(rgbIdx(frame)).folder, ...
        rgbFiles(rgbIdx(frame)).name);

    depthFile = fullfile( ...
        depthFiles(depthIdx(frame)).folder, ...
        depthFiles(depthIdx(frame)).name);

    rgb = imread(rgbFile);

    rgb = rectificar_rgb_racional( ...
        rgb, ...
        fx, fy, cx, cy, ...
        Dcolor);

    depth = imread(depthFile);

    [h, w, ~] = size(rgb);

    %% Project the extinguisher centre into the image

    uTarget = round( ...
        fx*targetCamera(1)/targetCamera(3) + cx + 1);

    vTarget = round( ...
        fy*targetCamera(2)/targetCamera(3) + cy + 1);

    if uTarget < 1 || uTarget > w
        continue
    end

    if vTarget < 1 || vTarget > h
        continue
    end

    %% Red-colour segmentation

    red = double(rgb(:,:,1));
    green = double(rgb(:,:,2));
    blue = double(rgb(:,:,3));

    colorMask = red > 60;
    colorMask = colorMask & red > 1.25*green;
    colorMask = colorMask & red > 1.25*blue;
    colorMask = colorMask & red-green > 20;
    colorMask = colorMask & red-blue > 20;

    %% Search window around the expected image position

    halfWidth = 120;
    halfHeight = 170;

    uMin = max(1, uTarget-halfWidth);
    uMax = min(w, uTarget+halfWidth);

    vMin = max(1, vTarget-halfHeight);
    vMax = min(h, vTarget+halfHeight);

    searchWindow = false(h,w);
    searchWindow(vMin:vMax, uMin:uMax) = true;

    colorMask = colorMask & searchWindow;

    %% Clean the binary mask

    colorMask = bwareaopen(colorMask, 30);
    colorMask = imopen(colorMask, strel('disk',2));
    colorMask = imclose(colorMask, strel('disk',4));
    colorMask = imfill(colorMask, 'holes');

    components = bwconncomp(colorMask, 8);

    if components.NumObjects == 0
        continue
    end

    properties = regionprops( ...
        components, ...
        'Area', ...
        'Centroid', ...
        'PixelIdxList');

    areas = zeros(components.NumObjects,1);
    distances = zeros(components.NumObjects,1);

    for j = 1:components.NumObjects

        areas(j) = properties(j).Area;

        distances(j) = norm( ...
            properties(j).Centroid - ...
            [uTarget vTarget]);
    end

    candidates = find( ...
        areas >= 30 & ...
        distances <= 150);

    if isempty(candidates)
        continue
    end

    scores = areas(candidates) ./ ...
        (1 + (distances(candidates)/40).^2);

    [~, bestCandidate] = max(scores);

    selected = candidates(bestCandidate);

    mask = false(h,w);
    mask(properties(selected).PixelIdxList) = true;

    mask = imclose(mask, strel('disk',3));
    mask = imfill(mask, 'holes');
    mask = imdilate(mask, strel('disk',1));

    %% Extract depth values inside the mask

    linearIndices = find(mask);

    [v,u] = ind2sub( ...
        [h w], ...
        linearIndices);

    z = double(depth(linearIndices)) / 1000;

    validDepth = isfinite(z);
    validDepth = validDepth & z > minDepth;
    validDepth = validDepth & z < maxDepth;

    validDepth = validDepth & ...
        abs(z-targetCamera(3)) < 0.45;

    u = u(validDepth);
    v = v(validDepth);
    z = z(validDepth);

    if numel(z) < 80
        continue
    end

    %% Remove background points using depth consistency

    medianDepth = median(z);

    validDepth = abs(z-medianDepth) < 0.18;

    u = u(validDepth);
    v = v(validDepth);
    z = z(validDepth);

    if numel(z) < 80
        continue
    end

    %% Reconstruct the segmented object in 3D

    x = (double(u)-1-cx).*z/fx;
    y = (double(v)-1-cy).*z/fy;

    xyz = [x y z];

    objectCloud = pointCloud(single(xyz));

    objectCloud = pcdenoise( ...
        objectCloud, ...
        'NumNeighbors', 8, ...
        'Threshold', 1);

    xyz = double(reshape( ...
        objectCloud.Location, ...
        [], 3));

    xyz = xyz(all(isfinite(xyz),2), :);

    numPoints(k) = size(xyz,1);

    if numPoints(k) < 80
        continue
    end

    %% Estimate dimensions in the PCA coordinate system

    center = median(xyz, 1);
    centered = xyz-center;

    [~,~,principalAxes] = svd( ...
        centered, ...
        'econ');

    coordinates = centered*principalAxes;

% Identify the longitudinal axis and the diameter axis
roughLower = prctile(coordinates, 2.5, 1);
roughUpper = prctile(coordinates, 97.5, 1);

roughDimensions = roughUpper-roughLower;

[~, axisOrder] = sort( ...
    roughDimensions, ...
    'descend');

heightCoordinates = ...
    coordinates(:, axisOrder(1));

diameterCoordinates = ...
    coordinates(:, axisOrder(2));

% Conservative height percentiles suppress the handle and other points
% located at the longitudinal extremes of the object.
estimatedHeight = ...
    prctile(heightCoordinates, 97.5) - ...
    prctile(heightCoordinates, 2.5);

% Keep almost the entire silhouette when estimating the diameter.
% Only 0.25 percent is removed from each end.
estimatedDiameter = ...
    prctile(diameterCoordinates, 99.75) - ...
    prctile(diameterCoordinates, 0.25);

estimatedVolume = ...
    pi*(estimatedDiameter/2)^2 * ...
    estimatedHeight * 1000;

    shapeRatio = ...
        estimatedHeight / estimatedDiameter;

    %% Broad plausibility filter used by the baseline

    plausible = estimatedHeight >= 0.25;
    plausible = plausible && estimatedHeight <= 0.80;

    plausible = plausible && estimatedDiameter >= 0.08;
    plausible = plausible && estimatedDiameter <= 0.35;

    plausible = plausible && shapeRatio >= 1.5;
    plausible = plausible && shapeRatio <= 6.0;

    plausible = plausible && estimatedVolume >= 1;
    plausible = plausible && estimatedVolume <= 40;

    if ~plausible

        fprintf([ ...
            'KF %2d | Rejected  | %4d points | ' ...
            'H %.1f cm | D %.1f cm | V %.2f L\n'], ...
            frame, ...
            numPoints(k), ...
            100*estimatedHeight, ...
            100*estimatedDiameter, ...
            estimatedVolume)

        continue
    end

    heightM(k) = estimatedHeight;
    diameterM(k) = estimatedDiameter;
    volumeL(k) = estimatedVolume;

    candidate(k) = true;
    objectPoints{k} = xyz;

    fprintf([ ...
        'KF %2d | Candidate | %4d points | ' ...
        'H %.1f cm | D %.1f cm | V %.2f L\n'], ...
        frame, ...
        numPoints(k), ...
        100*heightM(k), ...
        100*diameterM(k), ...
        volumeL(k))
end

%% Baseline result

candidateIndices = find(candidate);

if isempty(candidateIndices)
    error('No valid measurement could be obtained.')
end

baselineHeight = median( ...
    heightM(candidate), ...
    'omitnan');

baselineDiameter = median( ...
    diameterM(candidate), ...
    'omitnan');

baselineVolume = median( ...
    volumeL(candidate), ...
    'omitnan');

baselineVolumeQ1 = prctile( ...
    volumeL(candidate), 25);

baselineVolumeQ3 = prctile( ...
    volumeL(candidate), 75);

%% Select complete views

% The 90th percentile of the measured height is used as the reference.
% Partial views generally produce considerably smaller heights.

heightReference = prctile( ...
    heightM(candidate), 90);

completeView = candidate;
completeView = completeView & ...
    heightM >= 0.85*heightReference;

completeView = completeView & ...
    heightM <= 1.10*heightReference;

if nnz(completeView) < 5
    warning('Too few complete views. All baseline candidates will be used.')
    completeView = candidate;
end

%% Robust diameter consensus

diametersComplete = diameterM(completeView);

diameterCenter = median( ...
    diametersComplete, ...
    'omitnan');

diameterMAD = median( ...
    abs(diametersComplete-diameterCenter), ...
    'omitnan');

diameterSigma = max( ...
    1.4826*diameterMAD, ...
    0.005);

diameterConsistent = completeView;
diameterConsistent = diameterConsistent & ...
    abs(diameterM-diameterCenter) <= ...
    2.5*diameterSigma;

if nnz(diameterConsistent) < 5
    warning('Too few consistent diameter estimates. All complete views will be used.')
    diameterConsistent = completeView;
end

%% Robust volume consensus

volumesConsistent = volumeL(diameterConsistent);

volumeCenter = median( ...
    volumesConsistent, ...
    'omitnan');

volumeMAD = median( ...
    abs(volumesConsistent-volumeCenter), ...
    'omitnan');

volumeSigma = max( ...
    1.4826*volumeMAD, ...
    0.50);

accepted = diameterConsistent;
accepted = accepted & ...
    abs(volumeL-volumeCenter) <= ...
    2.5*volumeSigma;

if nnz(accepted) < 5
    warning('Too few final measurements. The diameter-consensus views will be used.')
    accepted = diameterConsistent;
end

acceptedIndices = find(accepted);

%% Multi-view cylindrical result

finalHeight = median( ...
    heightM(accepted), ...
    'omitnan');

finalDiameter = median( ...
    diameterM(accepted), ...
    'omitnan');

finalVolumeMedian = median( ...
    volumeL(accepted), ...
    'omitnan');

% Compute the final result from the multi-view dimensions while retaining
% the cylindrical tank model.

finalVolume = ...
    pi*(finalDiameter/2)^2 * ...
    finalHeight * 1000;

heightQ1 = prctile(heightM(accepted), 25);
heightQ3 = prctile(heightM(accepted), 75);

diameterQ1 = prctile(diameterM(accepted), 25);
diameterQ3 = prctile(diameterM(accepted), 75);

volumeQ1 = prctile(volumeL(accepted), 25);
volumeQ3 = prctile(volumeL(accepted), 75);

%% Comparison with the reference volume

groundTruthVolume = 10;

baselineError = ...
    100*abs(baselineVolume-groundTruthVolume) / ...
    groundTruthVolume;

finalError = ...
    100*abs(finalVolume-groundTruthVolume) / ...
    groundTruthVolume;
fprintf('\n========== MULTI-VIEW FILTERING ==========\n')
fprintf('Baseline candidates: %d\n', nnz(candidate))
fprintf('Complete views: %d\n', nnz(completeView))
fprintf('Consistent diameters: %d\n', nnz(diameterConsistent))
fprintf('Final keyframes: %d\n', nnz(accepted))

fprintf('\nKeyframes used:\n')
fprintf('%d ', double(keyFrameIDs(accepted)))
fprintf('\n')

fprintf('\n========== COMPARISON ==========\n')

fprintf('Baseline:\n')
fprintf('  Median height: %.1f cm\n', 100*baselineHeight)
fprintf('  Median diameter: %.1f cm\n', 100*baselineDiameter)
fprintf('  Median volume: %.2f L\n', baselineVolume)
fprintf('  Absolute percentage error: %.1f %%\n', baselineError)

fprintf('\nRobust method:\n')
fprintf('  Median height: %.1f cm\n', 100*finalHeight)
fprintf('  Median diameter: %.1f cm\n', 100*finalDiameter)
fprintf('  Cylindrical volume: %.2f L\n', finalVolume)
fprintf('  Median volume per keyframe: %.2f L\n', finalVolumeMedian)
fprintf('  Interquartile range: %.2f - %.2f L\n', ...
    volumeQ1, volumeQ3)
fprintf('  Absolute percentage error: %.1f %%\n', finalError)

%% Select the most representative keyframe

heightScale = max( ...
    1.4826*median( ...
    abs(heightM(accepted)-finalHeight), ...
    'omitnan'), ...
    0.01);

diameterScale = max( ...
    1.4826*median( ...
    abs(diameterM(accepted)-finalDiameter), ...
    'omitnan'), ...
    0.005);

volumeScale = max( ...
    1.4826*median( ...
    abs(volumeL(accepted)-finalVolume), ...
    'omitnan'), ...
    0.50);

bestScore = ...
    abs(heightM(accepted)-finalHeight)/heightScale + ...
    abs(diameterM(accepted)-finalDiameter)/diameterScale + ...
    abs(volumeL(accepted)-finalVolume)/volumeScale;

[~, position] = min(bestScore);

bestIndex = acceptedIndices(position);
bestFrame = double(keyFrameIDs(bestIndex));

bestXYZ = objectPoints{bestIndex};

bestCloud = pointCloud(single(bestXYZ));

bestColor = repmat( ...
    uint8([210 40 35]), ...
    bestCloud.Count, ...
    1);

bestCloud = pointCloud( ...
    bestCloud.Location, ...
    'Color', bestColor);

